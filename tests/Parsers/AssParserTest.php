    #[DataProvider("realFiles")]
    public function testRealFileParses(string $file, int $cueCount, array $first, array $last): void
    {
        $cues = $this->parseFile($file)->getCues();

        $this->assertSame($cueCount, count($cues));
        $this->assertSame($first, [$cues[0]->getStart(), $cues[0]->getEnd(), $cues[0]->getLines()]);
        $this->assertSame($last, [end($cues)->getStart(), end($cues)->getEnd(), end($cues)->getLines()]);
    }


    public function testAegisubFileKeepsHeaderStylesAndComments(): void
    {
        $subtitle = $this->parseFile("own_aegisub.ass");
        $data     = $subtitle->findFormatData("ass");

        $this->assertSame("Morning train to the coast", $subtitle->findMetadata(Subtitle::METADATA_TITLE));
        $this->assertSame(["; Script generated by Aegisub 3.2.2", "; http://www.aegisub.org/"], $data["scriptInfoComments"]);
        $this->assertSame("1920", $data["scriptInfo"]["PlayResX"]);
        $this->assertArrayNotHasKey("Title", $data["scriptInfo"]);
        $this->assertSame(["Script Info", "Aegisub Project Garbage", "V4+ Styles", "Events"], $data["sectionOrder"]);
        $this->assertSame("Last Style Storage: Default", $data["sections"]["Aegisub Project Garbage"][0]);
        $this->assertSame(["Default", "Top", "Karaoke"], array_column($data["styles"], "Name"));
        $this->assertSame("Verdana", $data["styles"][2]["Fontname"]);
        $this->assertEquals(
            [
                new Comment("{\\r\\t(\$start,\$end,\\fscx120\\fscy120)\\t(\$end,\$end,\\fscx100\\fscy100)}", 0),
                new Comment("Check the platform number against the station sign", 2),
                new Comment("End of the station scene", 7),
            ],
            $subtitle->getComments()
        );
    }


    public function testAegisubFileConvertsOverrideTagsAndKaraoke(): void
    {
        $cues = $this->parseFile("own_aegisub.ass")->getCues();

        $this->assertSame(["<v Conductor>The train to the coast", "leaves from platform four."], $cues[1]->getLines());
        $this->assertSame(["Platform 4: <font color=\"#ffd700\">Coast Express</font>"], $cues[3]->getLines());
        $this->assertSame(Alignment::TopCenter, $cues[3]->getAlignment());
        $this->assertSame(
            ["<b><00:00:13.500>The <00:00:13.900>train <00:00:14.250>leaves <00:00:14.750>at <00:00:15.350>noon</b>"],
            $cues[5]->getLines()
        );
        $this->assertSame(
            ["Layer" => "0", "Style" => "Default", "Name" => "Passenger", "MarginL" => "0", "MarginR" => "0", "MarginV" => "0", "Effect" => ""],
            $cues[2]->findFormatData("ass")["fields"]
        );
        $this->assertSame("{\\i1}Is it on time{\\i0} today?", $cues[2]->findFormatData("ass")["text"]);
    }


    public function testSignsFileSortsCuesAndSkipsDrawingsAndUnknownTags(): void
    {
        $subtitle = $this->parseFile("own_signs_crlf.ass");
        $cues     = $subtitle->getCues();

        $this->assertSame(["<v Reporter>Clouds move in from the west during the night."], $cues[1]->getLines());
        $this->assertSame(["SUNNY", "25 °C"], $cues[2]->getLines());
        $this->assertSame("1", $cues[2]->findFormatData("ass")["fields"]["Layer"]);
        $this->assertSame([], $cues[3]->getLines());
        $this->assertSame(Alignment::TopLeft, $cues[3]->getAlignment());
        $this->assertSame(["<v Reporter>Expect light rain,\u{00A0}mostly after 10\u{00A0}pm."], $cues[4]->getLines());
        $this->assertSame(["<b><i>Tomorrow:</i></b> dry and windy"], $cues[5]->getLines());

        $sections = $subtitle->findFormatData("ass")["sections"];
        $this->assertSame("fontname: WeatherSans_0.ttf", $sections["Fonts"][0]);
        $this->assertSame("filename: sun.png", $sections["Graphics"][0]);
        $this->assertSame(3, count($sections["Graphics"]));
    }


    public function testSsaFileReadsMarkedColumnAndLegacyAlignment(): void
    {
        $subtitle = $this->parseFile("own_ssa_v4.ssa");
        $cues     = $subtitle->getCues();
        $data     = $subtitle->findFormatData("ass");

        $this->assertSame("V4 Styles", $data["stylesSection"]);
        $this->assertSame(AssFormatLines::SSA_EVENT_FORMAT, $data["eventFormat"]);
        $this->assertSame("-2147483640", $data["styles"][0]["BackColour"]);
        $this->assertSame(Alignment::TopCenter, $cues[1]->getAlignment());
        $this->assertSame("Marked=1", $cues[2]->findFormatData("ass")["fields"]["Marked"]);
        $this->assertSame("!Effect", $cues[3]->findFormatData("ass")["fields"]["Effect"]);
        $this->assertEquals([new Comment("Timetable section", 1)], $subtitle->getComments());
    }


    public function testStyleFlagsAndAlignmentApplyToTheCues(): void
    {
        $cues = $this->parseFile("own_style_flags.ass")->getCues();

        $this->assertSame([
            [["<v Driver>Last stop is the depot."], Alignment::BottomCenter],
            [["<i>I should have taken the earlier bus.</i>"], Alignment::TopCenter],
            [["<i>Maybe the driver</i> knows a shortcut."], Alignment::BottomCenter],
            [["<b><u><s>Depot closed for repairs</s></u></b>"], Alignment::TopLeft],
            [["The bus turns left at the bridge."], Alignment::BottomCenter],
            [["<i><b>Left</b></i><i> again</i><b><u><s> already</s></u></b>"], Alignment::TopCenter],
        ], array_map(fn (SubtitleCue $cue): array => [$cue->getLines(), $cue->getAlignment()], $cues));
    }


    public function testStyleItalicsAndAlignmentReachSubRip(): void
    {
        $this->assertStringContainsString(
            "00:00:03,200 --> 00:00:05,400\n{\\an8}<i>I should have taken the earlier bus.</i>\n",
            $this->parseFile("own_style_flags.ass")->toString(Format::SubRip)
        );
    }


    public function testStylesAfterTheEventsSectionStillApply(): void
    {
        $cue = $this->parseEvents(
            self::EVENTS_HEADER . "Dialogue: 0,0:00:01.00,0:00:02.00,*Thoughts,,0,0,0,,Hmm\n\n" .
            "[V4+ Styles]\nFormat: Name, Italic, Alignment\nStyle: Thoughts,-1,9\n"
        )->getCues()[0];

        $this->assertSame([["<i>Hmm</i>"], Alignment::TopRight], [$cue->getLines(), $cue->getAlignment()]);
    }


    public function testSsaStyleUsesTheLegacyAlignmentCode(): void
    {
        $cue = $this->parseEvents(
            "[V4 Styles]\nFormat: Name, Bold, Italic, Alignment\nStyle: Default,-1,0,6\n\n" .
            "[Events]\nFormat: Marked, Start, End, Style, Text\nDialogue: Marked=0,0:00:01.00,0:00:02.00,Other,Hello\n"
        )->getCues()[0];

        $this->assertSame([["<b>Hello</b>"], Alignment::TopCenter], [$cue->getLines(), $cue->getAlignment()]);
    }


    public function testCommentEventStaysBeforeItsEventWhenTheEventsAreOutOfTimeOrder(): void
    {
        $subtitle = $this->parseFile("own_comment_before_earlier_event.ass");

        $this->assertSame(["The door opens.", "The shop is open.", "The shop closes."], array_map(fn (SubtitleCue $cue) => $cue->getText(), $subtitle->getCues()));
        $this->assertEquals([
            new Comment("The door opens before the shop", 0),
            new Comment("The shop opens at nine", 1),
            new Comment("End of the shop scene", 3),
        ], $subtitle->getComments());
    }


    public function testColumnsAreMappedByName(): void
    {
        $cue = $this->parseEvents(
            "[Events]\nFormat: Name, End, Start, Style, Text\nDialogue: Ann,0:00:05.00,0:00:04.00,Default,Hi, you\n"
        )->getCues()[0];

        $this->assertSame([4.0, 5.0, ["<v Ann>Hi, you"]], [$cue->getStart(), $cue->getEnd(), $cue->getLines()]);
    }


    public static function overrideTags(): array
    {
        return [
            "bold and italic"            => ["{\\b1}a{\\b0} {\\i1}b{\\i0}", ["<b>a</b> <i>b</i>"]],
            "open tag closes at the end" => ["{\\u1}a", ["<u>a</u>"]],
            "empty value resets"         => ["{\\s1}a{\\s}b", ["<s>a</s>b"]],
            "weight is no core markup"   => ["{\\b700}a", ["a"]],
            "BGR colour"                 => ["{\\c&H0000FF&}red", ["<font color=\"#ff0000\">red</font>"]],
            "primary colour"             => ["{\\1c&HFF0000&}blue", ["<font color=\"#0000ff\">blue</font>"]],
            "short colour"               => ["{\\c&HFF&}red", ["<font color=\"#ff0000\">red</font>"]],
            "colour reset"               => ["{\\c&H00FF00&}a{\\c}b", ["<font color=\"#00ff00\">a</font>b"]],
            "border colour is dropped"   => ["{\\3c&H0000FF&}a", ["a"]],
            "tags nest"                  => ["{\\b1}a{\\i1}b{\\b0}c{\\i0}d", ["<b>a<i>b</i></b><i>c</i>d"]],
            "reset closes all"           => ["{\\b1\\i1}a{\\r}b", ["<b><i>a</i></b>b"]],
            "reset to style"             => ["{\\b1}a{\\rSign}b", ["<b>a</b>b"]],
            "animation is skipped"       => ["{\\t(0,500,\\b1\\1c&H0000FF&)}a", ["a"]],
            "comment block"              => ["a{note}b", ["ab"]],
            "drawing"                    => ["{\\p1}m 0 0 l 10 0{\\p0}text", ["text"]],
            "escaped text"               => ["1 < 2 & 3 > 2", ["1 &lt; 2 &amp; 3 &gt; 2"]],
            "hard break"                 => ["a\\Nb", ["a", "b"]],
            "soft break"                 => ["a\\nb", ["a b"]],
            "hard space"                 => ["a\\hb", ["a\u{00A0}b"]],
        ];
    }


