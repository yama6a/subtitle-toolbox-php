    public function testKaraokeTagsBecomeWordTimestamps(): void
    {
        $cue = $this->parseEvents(self::EVENTS_HEADER . "Dialogue: 0,0:01:00.00,0:01:05.00,Default,,0,0,0,,{\\k50}Ka{\\kf25}ra{\\K100}o{\\ko12.5}ke\n")->getCues()[0];

        $this->assertSame(["<00:01:00.000>Ka<00:01:00.500>ra<00:01:00.750>o<00:01:01.750>ke"], $cue->getLines());
    }


    public function testSoftBreakIsAHardBreakInWrapStyle2(): void
    {
        $cue = $this->parseEvents("[Script Info]\nWrapStyle: 2\n\n" . self::EVENTS_HEADER . "Dialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,a\\nb\n")->getCues()[0];

        $this->assertSame(["a", "b"], $cue->getLines());
    }


    public function testNameBecomesSpeakerOnTheFirstTextLine(): void
    {
        $cue = $this->parseEvents(self::EVENTS_HEADER . "Dialogue: 0,0:00:01.00,0:00:02.00,Default,A<B,0,0,0,,{\\an8}\\N  Hi\n")->getCues()[0];

        $this->assertSame(["<v A&lt;B>Hi"], $cue->getLines());
    }


    public function testWindows1252FileReadAsUtf8KeepsItsLinesAndSpeaker(): void
    {
        $lines = array_map(
            fn (SubtitleCue $cue): array => array_map(fn (string $line): string => iconv("Windows-1252", "UTF-8", $line), $cue->getLines()),
            Subtitle::fromString(file_get_contents(__DIR__ . "/../files/ass/own_windows_1252.ass"), Format::Ass, new ReadOptions(encoding: "UTF-8"))->getCues()
        );

        $this->assertSame([
            ["<v Hélène>Le café ouvre à sept heures."],
            ["<i>Crème brûlée</i>", "à 4 €"],
            ["<v Hélène>See you tomorrow."],
        ], $lines);
    }


    public function testTimesAcceptOneToThreeFractionDigits(): void
    {
        $cue = $this->parseEvents(self::EVENTS_HEADER . "Dialogue: 0,10:00:01.5,10:00:02.125,Default,,0,0,0,,a\n")->getCues()[0];

        $this->assertSame([36001.5, 36002.125], [$cue->getStart(), $cue->getEnd()]);
    }


    public function testEventsWithoutFormatLineUseTheDefaultColumns(): void
    {
        $subtitle = $this->parseEvents("[Script Info]\nScriptType: v4.00\n\n[Events]\nDialogue: Marked=0,0:00:01.00,0:00:02.00,Default,,0,0,0,,Hi\n");

